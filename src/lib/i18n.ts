import { xEn, xHi, xMr } from './x';

const dicts: Record<Language, Dict> = {
  en: { ...en, ...xEn },
  hi: { ...hi, ...xHi },
  mr: { ...mr, ...xMr },
};

export const LANGS: { code: Language; label: string; native: string }[] = [
  { code: 'en', label: 'English', native: 'English' },
  { code: 'hi', label: 'Hindi', native: 'हिन्दी' },
  { code: 'mr', label: 'Marathi', native: 'मराठी' },
];

export function makeT(lang: Language) {
  return (key: string, vals?: Record<string, string | number | undefined>): string => {
    const d = dicts[lang] ?? en;
    let s = d[key] ?? en[key] ?? key;
    if (vals) {
      for (const k of Object.keys(vals)) {
        s = s.split(`{${k}}`).join(String(vals[k] ?? ''));
      }
    }
    return s;
  };
}